use crate::kernel::bore;
use crate::power::profiles;
use serde::{Deserialize, Serialize};
use std::sync::atomic::{AtomicU8, Ordering};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum PowerPreset {
    Battery = 0,
    Balanced = 1,
    LowLatency = 2,
    Gaming = 3,
}

static ACTIVE_PRESET: AtomicU8 = AtomicU8::new(1); // Default to Balanced

impl PowerPreset {
    pub fn name(&self) -> &'static str {
        match self {
            PowerPreset::Battery => "Battery / Silent",
            PowerPreset::Balanced => "Balanced",
            PowerPreset::LowLatency => "Low-Latency / Workstation",
            PowerPreset::Gaming => "Max Performance / Gaming",
        }
    }

    pub fn from_u8(val: u8) -> Self {
        match val {
            0 => PowerPreset::Battery,
            2 => PowerPreset::LowLatency,
            3 => PowerPreset::Gaming,
            _ => PowerPreset::Balanced,
        }
    }

    pub fn as_u8(&self) -> u8 {
        *self as u8
    }
}

pub fn get_active_preset() -> PowerPreset {
    PowerPreset::from_u8(ACTIVE_PRESET.load(Ordering::SeqCst))
}

pub fn set_active_preset(preset: PowerPreset) {
    ACTIVE_PRESET.store(preset.as_u8(), Ordering::SeqCst);
}

/// Applies a complete Mithrandir power & kernel scheduler preset.
pub fn apply_preset(preset: PowerPreset) -> Result<(), String> {
    let (ppd_profile, governor, epp, boost, aspm, bore_val) = match preset {
        PowerPreset::Battery => (
            "power-saver",
            "powersave",
            "power",
            false,
            "powersupersave",
            false,
        ),
        PowerPreset::Balanced => (
            "balanced",
            "schedutil",
            "balance_performance",
            true,
            "default",
            true,
        ),
        PowerPreset::LowLatency => (
            "performance",
            "performance",
            "balance_performance",
            true,
            "default",
            true,
        ),
        PowerPreset::Gaming => (
            "performance",
            "performance",
            "performance",
            true,
            "default",
            true,
        ),
    };

    // 1. power-profiles-daemon (unprivileged D-Bus call)
    let _ = profiles::set_power_profiles_daemon_profile(ppd_profile);

    // 2. Hardware Tunables (sysfs & procfs)
    // Attempt direct write first
    let mut needs_privileged_helper = false;

    if bore::is_bore_supported() {
        if let Err(e) = bore::set_bore_state(bore_val) {
            if is_permission_error(&e) {
                needs_privileged_helper = true;
            }
        }
    }

    if let Err(e) = profiles::set_governor(governor) {
        if is_permission_error(&e) {
            needs_privileged_helper = true;
        }
    }

    if let Err(e) = profiles::set_epp(epp) {
        if is_permission_error(&e) {
            needs_privileged_helper = true;
        }
    }

    if profiles::is_turbo_boost_supported() {
        if let Err(e) = profiles::set_turbo_boost(boost) {
            if is_permission_error(&e) {
                needs_privileged_helper = true;
            }
        }
    }

    let _ = profiles::set_aspm_policy(aspm);

    // 4. If direct write needed root elevation, call privileged helper via pkexec
    if needs_privileged_helper {
        run_privileged_helper(Some(bore_val), Some(governor), Some(epp), Some(boost), Some(aspm), false)?;
    }

    set_active_preset(preset);
    Ok(())
}

fn is_permission_error(e: &str) -> bool {
    let el = e.to_lowercase();
    el.contains("permission denied") || el.contains("os error 13") || el.contains("operation not permitted")
}

/// Executes the privileged kernel & power state changes via `HostBridge::run_privileged` (compatible with both host and Flatpak sandbox).
pub fn run_privileged_helper(
    bore: Option<bool>,
    governor: Option<&str>,
    epp: Option<&str>,
    boost: Option<bool>,
    aspm: Option<&str>,
    persist: bool,
) -> Result<(), String> {
    let mut cmds = Vec::new();

    if let Some(b) = bore {
        let val = if b { "1" } else { "0" };
        cmds.push(format!(
            "[ -e /proc/sys/kernel/sched_bore ] && echo {} > /proc/sys/kernel/sched_bore || true",
            val
        ));
        if persist {
            cmds.push(format!(
                "mkdir -p /etc/sysctl.d && printf '# Generated by Mithrandir Kernel & Power Manager\\nkernel.sched_bore = {}\\n' > /etc/sysctl.d/99-mithrandir-scheduler.conf",
                val
            ));
        }
    }

    if let Some(g) = governor {
        cmds.push(format!(
            "for f in /sys/devices/system/cpu/cpu[0-9]*/cpufreq/scaling_governor; do [ -e \"$f\" ] && echo '{}' > \"$f\" 2>/dev/null || true; done",
            g.trim()
        ));
    }

    if let Some(ep) = epp {
        cmds.push(format!(
            "for f in /sys/devices/system/cpu/cpu[0-9]*/cpufreq/energy_performance_preference; do [ -e \"$f\" ] && echo '{}' > \"$f\" 2>/dev/null || true; done",
            ep.trim()
        ));
    }

    if let Some(bt) = boost {
        let intel_val = if bt { "0" } else { "1" };
        let amd_val = if bt { "1" } else { "0" };
        cmds.push(format!(
            "[ -e /sys/devices/system/cpu/intel_pstate/no_turbo ] && echo {} > /sys/devices/system/cpu/intel_pstate/no_turbo 2>/dev/null || true; [ -e /sys/devices/system/cpu/cpufreq/boost ] && echo {} > /sys/devices/system/cpu/cpufreq/boost 2>/dev/null || true",
            intel_val, amd_val
        ));
    }

    if let Some(asp) = aspm {
        cmds.push(format!(
            "[ -e /sys/module/pcie_aspm/parameters/policy ] && echo '{}' > /sys/module/pcie_aspm/parameters/policy 2>/dev/null || true",
            asp.trim()
        ));
    }

    if cmds.is_empty() {
        return Ok(());
    }

    let script = cmds.join("; ");
    let (code, _, stderr) = crate::backend::host_bridge::HostBridge::run_privileged(&["sh", "-c", &script])?;
    if code == 0 {
        Ok(())
    } else {
        Err(format!("Privileged helper failed: {}", stderr.trim()))
    }
}

/// Directly applies kernel & power tunables with root privileges (called by `mithrandir --apply-kernel-state`).
pub fn apply_kernel_state_privileged(
    bore: Option<bool>,
    governor: Option<&str>,
    epp: Option<&str>,
    boost: Option<bool>,
    aspm: Option<&str>,
    persist: bool,
) -> Result<(), String> {
    if let Some(b) = bore {
        if bore::is_bore_supported() {
            let _ = bore::set_bore_state(b);
        }
        if persist {
            let _ = bore::persist_bore_state(b);
        }
    }

    if let Some(gov) = governor {
        let _ = profiles::set_governor(gov);
    }

    if let Some(ep) = epp {
        let _ = profiles::set_epp(ep);
    }

    if let Some(bt) = boost {
        if profiles::is_turbo_boost_supported() {
            let _ = profiles::set_turbo_boost(bt);
        }
    }

    if let Some(asp) = aspm {
        let _ = profiles::set_aspm_policy(asp);
    }

    Ok(())
}
