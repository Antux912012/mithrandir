use std::fs;
use std::path::Path;

pub const DEFAULT_BORE_SYSCTL_PATH: &str = "/proc/sys/kernel/sched_bore";
pub const DEFAULT_BORE_PERSIST_CONF: &str = "/etc/sysctl.d/99-mithrandir-scheduler.conf";

/// Reads the kernel release string from `/proc/sys/kernel/osrelease` or via `uname -r`.
pub fn get_kernel_release() -> String {
    if let Ok(content) = fs::read_to_string("/proc/sys/kernel/osrelease") {
        let trimmed = content.trim();
        if !trimmed.is_empty() {
            return trimmed.to_string();
        }
    }

    if let Ok(output) = std::process::Command::new("uname").arg("-r").output() {
        if output.status.success() {
            return String::from_utf8_lossy(&output.stdout).trim().to_string();
        }
    }

    "unknown".to_string()
}

/// Checks whether a specific kernel release string indicates a CachyOS or BORE kernel.
pub fn is_cachyos_kernel_release(release: &str) -> bool {
    let rel_lower = release.to_lowercase();
    rel_lower.contains("cachyos") || rel_lower.contains("bore")
}

/// Detects whether the current kernel is CachyOS or has BORE scheduler patches.
pub fn is_cachyos_kernel(release: &str) -> bool {
    if is_cachyos_kernel_release(release) {
        return true;
    }

    if let Ok(version_str) = fs::read_to_string("/proc/version") {
        let v_lower = version_str.to_lowercase();
        if v_lower.contains("cachyos") || v_lower.contains("bore") {
            return true;
        }
    }

    Path::new(DEFAULT_BORE_SYSCTL_PATH).exists()
}

/// Checks if BORE tunable (`sched_bore`) is available in `/proc/sys/kernel/sched_bore`.
pub fn is_bore_supported() -> bool {
    is_bore_supported_at(Path::new(DEFAULT_BORE_SYSCTL_PATH))
}

pub fn is_bore_supported_at(path: &Path) -> bool {
    path.exists()
}

/// Reads current BORE state:
/// - `Some(true)`: BORE active (`1`)
/// - `Some(false)`: EEVDF active (`0`)
/// - `None`: Not supported or unreadable
pub fn get_bore_state() -> Option<bool> {
    get_bore_state_from_path(Path::new(DEFAULT_BORE_SYSCTL_PATH))
}

pub fn get_bore_state_from_path(path: &Path) -> Option<bool> {
    let content = fs::read_to_string(path).ok()?;
    match content.trim() {
        "1" => Some(true),
        "0" => Some(false),
        _ => None,
    }
}

/// Sets the runtime BORE state (`1` for BORE, `0` for EEVDF).
pub fn set_bore_state(enable: bool) -> Result<(), String> {
    set_bore_state_to_path(Path::new(DEFAULT_BORE_SYSCTL_PATH), enable)
}

pub fn set_bore_state_to_path(path: &Path, enable: bool) -> Result<(), String> {
    if !path.exists() {
        return Err(format!("BORE sysctl path does not exist: {}", path.display()));
    }
    let val = if enable { "1\n" } else { "0\n" };
    fs::write(path, val).map_err(|e| format!("Failed to write to {}: {}", path.display(), e))
}

/// Persists the BORE state across reboots by writing `/etc/sysctl.d/99-mithrandir-scheduler.conf`.
pub fn persist_bore_state(enable: bool) -> Result<(), String> {
    persist_bore_state_to_path(Path::new(DEFAULT_BORE_PERSIST_CONF), enable)
}

pub fn persist_bore_state_to_path(conf_path: &Path, enable: bool) -> Result<(), String> {
    let parent = conf_path.parent().unwrap_or_else(|| Path::new("/etc/sysctl.d"));
    if !parent.exists() {
        fs::create_dir_all(parent).map_err(|e| format!("Failed to create {}: {}", parent.display(), e))?;
    }

    let val = if enable { 1 } else { 0 };
    let content = format!(
        "# Generated by Mithrandir Optimizer\nkernel.sched_bore = {}\n",
        val
    );

    fs::write(conf_path, content)
        .map_err(|e| format!("Failed to write persistent sysctl {}: {}", conf_path.display(), e))
}
